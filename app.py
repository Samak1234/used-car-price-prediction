import streamlit as st
import pandas as pd
from sklearn.linear_model import LinearRegression


# -----------------------------
# Page setup
# -----------------------------

st.set_page_config(
    page_title="Used Car Price Estimator",
    page_icon="🚗",
    layout="centered"
)


# -----------------------------
# Minimal custom styling
# -----------------------------

st.markdown(
    """
    <style>
        .block-container {
            max-width: 900px;
            padding-top: 3rem;
            padding-bottom: 3rem;
        }

        h1 {
            font-size: 2.6rem !important;
            font-weight: 700 !important;
            letter-spacing: -0.03em;
        }

        .subtitle {
            color: #6b7280;
            font-size: 1.05rem;
            margin-top: -0.5rem;
            margin-bottom: 2rem;
        }

        .result-box {
            padding: 1.4rem 1.5rem;
            border: 1px solid #e5e7eb;
            border-radius: 14px;
            margin-top: 1.5rem;
        }

        .result-label {
            color: #6b7280;
            font-size: 0.95rem;
            margin-bottom: 0.25rem;
        }

        .result-value {
            font-size: 2rem;
            font-weight: 700;
            letter-spacing: -0.02em;
        }

        .disclaimer {
            color: #9ca3af;
            font-size: 0.82rem;
            margin-top: 0.75rem;
        }

        div.stButton > button {
            width: 100%;
            border-radius: 10px;
            height: 3rem;
            font-weight: 600;
        }
    </style>
    """,
    unsafe_allow_html=True
)


# -----------------------------
# Load and prepare dataset
# -----------------------------

df = pd.read_csv("car_prediction_data.csv")
df = df.drop_duplicates()

df["Car_Age"] = df["Year"].max() - df["Year"]

X = df.drop("Selling_Price", axis=1)
y = df["Selling_Price"]

X = X.drop(["Car_Name", "Year"], axis=1)
X = pd.get_dummies(X, drop_first=True)


# -----------------------------
# Train model
# -----------------------------

model = LinearRegression()
model.fit(X, y)


# -----------------------------
# Header
# -----------------------------

st.title("Used Car Price Estimator")

st.markdown(
    '<p class="subtitle">Estimate the resale value of a used car using a machine learning model.</p>',
    unsafe_allow_html=True
)

st.divider()


# -----------------------------
# Input form
# -----------------------------

with st.form("car_price_form"):

    col1, col2 = st.columns(2)

    with col1:
        present_price = st.number_input(
            "Present Price (₹ lakh)",
            min_value=0.0,
            step=0.1
        )

        car_age = st.number_input(
            "Car Age",
            min_value=0,
            step=1
        )

        fuel_type = st.selectbox(
            "Fuel Type",
            ["Petrol", "Diesel", "CNG"]
        )

        transmission = st.selectbox(
            "Transmission",
            ["Manual", "Automatic"]
        )

    with col2:
        kms_driven = st.number_input(
            "Kilometers Driven",
            min_value=0,
            step=1000
        )

        owners = st.number_input(
            "Previous Owners",
            min_value=0,
            step=1
        )

        seller_type = st.selectbox(
            "Seller Type",
            ["Dealer", "Individual"]
        )

    st.write("")

    predict_button = st.form_submit_button(
        "Predict Price",
        use_container_width=True
    )


# -----------------------------
# Prediction
# -----------------------------

if predict_button:

    if present_price <= 0:
        st.error("Present price must be greater than 0.")

    elif kms_driven < 0:
        st.error("Kilometers driven cannot be negative.")

    elif car_age < 0:
        st.error("Car age cannot be negative.")

    elif owners < 0:
        st.error("Number of owners cannot be negative.")

    else:
        input_data = pd.DataFrame({
            "Present_Price": [present_price],
            "Kms_Driven": [kms_driven],
            "Owner": [owners],
            "Car_Age": [car_age],
            "Fuel_Type_Diesel": [fuel_type == "Diesel"],
            "Fuel_Type_Petrol": [fuel_type == "Petrol"],
            "Seller_Type_Individual": [seller_type == "Individual"],
            "Transmission_Manual": [transmission == "Manual"]
        })

        input_data = input_data[X.columns]

        predicted_price = model.predict(input_data)[0]

        if predicted_price < 0:
            st.warning(
                "The model produced an unrealistic negative prediction for these inputs."
            )

        else:
            st.markdown(
                f"""
                <div class="result-box">
                    <div class="result-label">Estimated Selling Price</div>
                    <div class="result-value">₹{predicted_price:.2f} lakh</div>
                    <div class="disclaimer">
                        This estimate is generated by a machine learning model
                        and should be treated as an indicative resale value.
                    </div>
                </div>
                """,
                unsafe_allow_html=True
            )


# -----------------------------
# Model details
# -----------------------------

st.divider()

st.subheader("Model details")

col1, col2, col3 = st.columns(3)

col1.metric("Current Model", "Linear Regression")
col2.metric("R²", "0.75")
col3.metric("RMSE", "2.52 lakh")